function makeSeedRecord(
  recordId: string,
  tenantId: string,
  assetId: string,
  assetName: string,
  sourceType: DmrvRecord['sourceType'],
  scope: DmrvRecord['scope'],
  quantity: number,
  unit: DmrvRecord['unit'],
  emissionsTco2e: number,
  validationStatus: DmrvRecord['validationStatus'],
  period: string,
  createdAt: string
): DmrvRecord {
  return {
    recordId,
    tenantId,
    assetId,
    assetName,
    sourceType,
    scope,
    quantity,
    unit,
    emissionsTco2e,
    validationStatus,
    lineageHash: computeLineageHash({
      tenantId,
      assetId,
      sourceType,
      quantity,
      period,
      timestamp: createdAt,
    }),
    period,
    createdByUid: 'seed_admin',
    createdAt,
  };
}

